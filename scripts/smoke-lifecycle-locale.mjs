import { _electron as electron } from 'playwright-core';
import { mkdtemp, cp, readFile } from 'node:fs/promises';
import { resolve, join } from 'node:path';
import assert from 'node:assert/strict';

const fixture = process.argv[2];
if (!fixture) throw Error('Pass an isolated smoke-ui-review fixture directory');
const dir = await mkdtemp(resolve('.tmp/lifecycle-locale-'));
await cp(fixture, dir, { recursive: true });
const executablePath = resolve('build/s1a/mac-arm64/FormaBot.app/Contents/MacOS/FormaBot');
const env = { ...process.env, FORMABOT_TEST_DATA_DIR: dir };
delete env.ELECTRON_RUN_AS_NODE;
let app;
try {
  app = await electron.launch({ executablePath, env });
  const page = await app.firstWindow();
  await page.locator('#workbench').waitFor();
  await page.locator('#task').fill('保留这份草稿 · draft stays');
  const pid = app.process().pid;
  const windowId = await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows().find(w => w.webContents.getURL().endsWith('/index.html')).id);
  const before = await page.evaluate(() => window.forma.state());
  const result = await app.evaluate(({ BrowserWindow }, id) => {
    const window = BrowserWindow.fromId(id);
    window.close();
    return { destroyed: window.isDestroyed(), visible: window.isVisible() };
  }, windowId);
  assert.deepEqual(result, { destroyed: false, visible: false });
  assert.equal(app.process().pid, pid);
  await app.evaluate(({ app }) => app.emit('activate'));
  assert.equal(await app.evaluate(({ BrowserWindow }, id) => BrowserWindow.fromId(id).isVisible(), windowId), true);
  assert.equal(await page.locator('#task').inputValue(), '保留这份草稿 · draft stays');
  const settingsEvent = app.waitForEvent('window');
  await page.locator('#settings-open').click();
  const settings = await settingsEvent;
  await settings.locator('#api-key').fill('unsaved-fixture');
  await settings.locator('[data-tab=general]').click();
  await settings.locator('#language').selectOption('en');
  await settings.getByRole('heading', { name: 'General', exact: true }).waitFor();
  await page.getByRole('button', { name: 'Settings', exact: true }).waitFor();
  assert.equal(await page.locator('#task').inputValue(), '保留这份草稿 · draft stays');
  const after = await page.evaluate(() => window.forma.state());
  for (const field of ['selected', 'workspace', 'conversations', 'messages']) assert.deepEqual(after.value[field], before.value[field]);
  await settings.screenshot({ path: join(dir, 'settings-english.png') });
  await settings.locator('[data-tab=model]').click();
  assert.equal(await settings.locator('#api-key').inputValue(),'unsaved-fixture');
  await settings.locator('[data-tab=general]').click();
  await app.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows().find(w=>w.webContents.getURL().endsWith('/settings.html')).setSize(640,500));
  assert.equal(await settings.locator('aside').evaluate(node=>node.scrollWidth<=node.clientWidth),true);
  await settings.screenshot({path:join(dir,'settings-english-narrow.png')});
  await settings.locator('#language').selectOption('zh-CN');
  await settings.getByRole('heading', { name: '常规', exact: true }).waitFor();
  await page.getByRole('button', { name: '设置', exact: true }).waitFor();
  await settings.locator('#language').selectOption('en');
  await settings.getByRole('heading', { name: 'General', exact: true }).waitFor();
  await app.close();
  app = await electron.launch({ executablePath, env });
  const restarted = await app.firstWindow();
  await restarted.getByRole('button', { name: 'Settings', exact: true }).waitFor();
  assert.equal(JSON.parse(await readFile(join(dir, 'settings.json'), 'utf8')).locale, 'en');
  console.log(`PASS: close keeps same process/window/draft; Dock activate restores; bilingual settings/main controls synchronize; user data unchanged; explicit quit and restart persist language. No live model task. Evidence ${dir}`);
} finally { await app?.close(); }
